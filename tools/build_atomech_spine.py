"""Bundle the Atomech Spine rigs (Phalanx and the claw probe) so the hit reaction deck can play them from file://.

Source: the Spine 4.3 web player exports that sit next to each rig in the Atomech art folder:
  C:/Projects/Art/Player/Phalanx/Phalanx.html
  C:/Projects/Art/Monster/ClawProbe/Phalanx.html   (despite the name, this one holds the claw probe)

  python tools/build_atomech_spine.py <phalanx export.html> <claw probe export.html>

Each export embeds a binary skeleton, an atlas and its PNG pages as base64. This pulls them out,
re-encodes the pages as lossless WebP and writes assets/spine/atomech-data.js,
which sets window.ATOMECH_SPINE = { phalanx: {...data URIs}, claw: {...} }.
"""
import base64, io, json, pathlib, re, sys
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'spine' / 'atomech-data.js'


def unpack(path, key):
    t = pathlib.Path(path).read_text(encoding='utf-8')
    skel = re.search(r"skeletonData = '([^']+)'", t).group(1)
    atlas = re.search(r"atlasData = '([^']+)'", t).group(1)
    uris = {f'{key}.skel': 'data:application/octet-stream;base64,' + skel,
            f'{key}.atlas': 'data:text/plain;base64,' + atlas}
    for name, png in re.findall(r'\["([^"]+\.png)", "([A-Za-z0-9+/=]+)"\]', t):
        buf = io.BytesIO()
        Image.open(io.BytesIO(base64.b64decode(png))).save(buf, 'WEBP', lossless=True, exact=True, method=6)   # lossless + exact: the pages hold premultiplied colour, which lossy WebP mangles at the edges
        uris[name] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    return uris


def main(phalanx, claw):
    data = {'phalanx': unpack(phalanx, 'phalanx'), 'claw': unpack(claw, 'claw')}
    OUT.write_text('// generated by tools/build_atomech_spine.py\nwindow.ATOMECH_SPINE = ' + json.dumps(data) + ';\n', encoding='utf-8')
    print(OUT, OUT.stat().st_size // 1024, 'KB')


if __name__ == '__main__':
    main(*sys.argv[1:3])
