"""Bundle the Forsaken "Basic Strikes" Spine mockups so the deck can play them from file://.

Steps (the first two use the Spine 4.3 CLI that ships with the editor):
  Spine.com -i "C:/Projects/MoonStudios/Forsaken/Design/Abilities/AbilityMockups.spine" -o out/spine -e json
  Spine.com -i "C:/Projects/MoonStudios/Forsaken/Design/Abilities/images" -o assets/spine -p forsaken
  python tools/build_spine.py "out/spine/Basic Strikes.json"

Writes assets/spine/basic-strikes.json (attachments whose image isn't in the atlas removed)
and assets/spine/spine-data.js, which holds the skeleton, atlas and texture as data URIs:
browsers won't let spine-player fetch files from a page opened straight off disk.
"""
import base64, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPINE = ROOT / 'assets' / 'spine'


def regions(atlas_text):
    lines = atlas_text.splitlines()
    # region names are the lines with no ':' that come after the page header block
    return {l.strip() for l in lines[1:] if l.strip() and ':' not in l and not l.endswith('.png')}


def main(src):
    skel = json.loads(pathlib.Path(src).read_text(encoding='utf-8'))
    atlas = (SPINE / 'forsaken.atlas').read_text(encoding='utf-8')
    have = regions(atlas)
    dropped = set()
    for skin in skel['skins']:
        for slot, atts in skin.get('attachments', {}).items():
            for name in list(atts):
                a = atts[name]
                if a.get('type', 'region') in ('region', 'mesh') and a.get('path', name) not in have:
                    dropped.add(a.get('path', name)); del atts[name]
    out = json.dumps(skel, separators=(',', ':'))
    (SPINE / 'basic-strikes.json').write_text(out, encoding='utf-8')

    def uri(mime, data): return f'data:{mime};base64,' + base64.b64encode(data).decode()
    js = 'window.SPINE_DATA = ' + json.dumps({
        'basic-strikes.json': uri('application/json', out.encode()),
        'forsaken.atlas': uri('text/plain', atlas.encode()),
        'forsaken.png': uri('image/png', (SPINE / 'forsaken.png').read_bytes()),
    }) + ';\n'
    (SPINE / 'spine-data.js').write_text('// generated by tools/build_spine.py\n' + js, encoding='utf-8')
    print('animations:', ', '.join(skel['animations']))
    print('dropped (image not in atlas):', ', '.join(sorted(dropped)) or 'none')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'out/spine/Basic Strikes.json')
